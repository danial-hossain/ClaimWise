# Palette constants
NAVY_PRIMARY = (0.08, 0.18, 0.36)       # #142E5C
BLUE_ACCENT = (0.13, 0.44, 0.88)        # #2170E0
GRAY_BG = (0.96, 0.97, 0.98)            # #F5F7FA
GRAY_BORDER = (0.82, 0.85, 0.88)        # #D1D9E0
TEXT_DARK = (0.12, 0.15, 0.18)          # #1F262E
TEXT_MUTED = (0.42, 0.46, 0.52)         # #6B7584
AMBER_WARNING = (0.85, 0.50, 0.05)      # #D9800D
WHITE = (1.0, 1.0, 1.0)


def _format_cents(cents: Optional[int]) -> str:
    """Format integer cents as USD string."""
    if cents is None:
        return "Unknown"
    negative = cents < 0
    abs_cents = abs(cents)
    dollars = abs_cents // 100
    remainder = abs_cents % 100
    formatted = f"${dollars:,}.{remainder:02d}"
    return f"-{formatted}" if negative else formatted


class PDFBuilder:
    """Helper class to construct styled multi-page PDF documents."""

    def __init__(self, title: str, subtitle: str):
        self.doc = pymupdf.open()
        self.page_width = 595.0   # A4 width (points)
        self.page_height = 842.0  # A4 height (points)
        self.margin_x = 40.0
        self.content_width = self.page_width - (2 * self.margin_x)
        self.current_y = 0.0
        self.title = title
        self.subtitle = subtitle
        self.page_number = 0
        self.new_page()

    def new_page(self):
        """Create a new page and render header and footer."""
        self.page = self.doc.new_page(width=self.page_width, height=self.page_height)
        self.page_number += 1

        # Header banner (Navy)
        self.page.draw_rect(
            pymupdf.Rect(0, 0, self.page_width, 54),
            color=NAVY_PRIMARY,
            fill=NAVY_PRIMARY,
        )
        self.page.insert_text(
            pymupdf.Point(self.margin_x, 26),
            "ClaimWise  |  " + self.title,
            fontname="helv",
            fontsize=13,
            color=WHITE,
        )
        self.page.insert_text(
            pymupdf.Point(self.margin_x, 42),
            "Tagline: Evidence first. If no proof, no answer.",
            fontname="helv",
            fontsize=8,
            color=(0.8, 0.88, 1.0),
        )

        # Footer
        footer_y = self.page_height - 24
        self.page.draw_line(
            pymupdf.Point(self.margin_x, footer_y - 8),
            pymupdf.Point(self.page_width - self.margin_x, footer_y - 8),
            color=GRAY_BORDER,
            width=0.5,
        )
        self.page.insert_text(
            pymupdf.Point(self.margin_x, footer_y),
            "Confidential  •  Generated by ClaimWise Engine  •  FinTechathon Prototype",
            fontname="helv",
            fontsize=7,
            color=TEXT_MUTED,
        )
        page_str = f"Page {self.page_number}"
        self.page.insert_text(
            pymupdf.Point(self.page_width - self.margin_x - 30, footer_y),
            page_str,
            fontname="helv",
            fontsize=7,
            color=TEXT_MUTED,
        )

        self.current_y = 74.0

    def check_space(self, required_height: float):
        """Ensure page has room for the next block, or spawn a new page."""
        if self.current_y + required_height > self.page_height - 50:
            self.new_page()

    def add_section_title(self, title: str):
        """Add a section heading."""
        self.check_space(32)
        self.page.draw_line(
            pymupdf.Point(self.margin_x, self.current_y + 16),
            pymupdf.Point(self.page_width - self.margin_x, self.current_y + 16),
            color=BLUE_ACCENT,
            width=1.2,
        )
        self.page.insert_text(
            pymupdf.Point(self.margin_x, self.current_y + 12),
            title.upper(),
            fontname="helv",
            fontsize=10,
            color=NAVY_PRIMARY,
        )
        self.current_y += 26

    def add_info_grid(self, items: List[tuple[str, str]]):
        """Render 2-column key-value grid."""
        rows = (len(items) + 1) // 2
        height = rows * 18 + 12
        self.check_space(height)

        rect = pymupdf.Rect(self.margin_x, self.current_y, self.page_width - self.margin_x, self.current_y + height)
        self.page.draw_rect(rect, color=GRAY_BORDER, fill=GRAY_BG)

        for idx, (label, val) in enumerate(items):
            col = idx % 2
            row = idx // 2
            x = self.margin_x + 12 + (col * (self.content_width / 2))
            y = self.current_y + 14 + (row * 18)

            self.page.insert_text(
                pymupdf.Point(x, y),
                f"{label}:",
                fontname="helv",
                fontsize=8,
                color=TEXT_MUTED,
            )
            self.page.insert_text(
                pymupdf.Point(x + 95, y),
                str(val),
                fontname="helv",
                fontsize=8,
                color=TEXT_DARK,
            )
        self.current_y += height + 14

    def add_disclaimer_box(self, text: str):
        """Render prominent disclaimer warning box."""
        self.check_space(54)
        rect = pymupdf.Rect(self.margin_x, self.current_y, self.page_width - self.margin_x, self.current_y + 44)
        self.page.draw_rect(rect, color=AMBER_WARNING, fill=(1.0, 0.97, 0.92))

        self.page.insert_text(
            pymupdf.Point(self.margin_x + 10, self.current_y + 14),
            "IMPORTANT NOTICE & SIMULATION DISCLAIMER",
            fontname="helv",
            fontsize=8,
            color=AMBER_WARNING,
        )
        self.page.insert_textbox(
            pymupdf.Rect(self.margin_x + 10, self.current_y + 18, self.page_width - self.margin_x - 10, self.current_y + 40),
            text,
            fontname="helv",
            fontsize=7,
            color=TEXT_DARK,
        )
        self.current_y += 54


class PDFExportService:
    """Service generating Explanation of Benefits, Appeal Letter, and Comparison PDFs."""

    @staticmethod
    def generate_eob_pdf(claim: ClaimRecord, eob: ExplanationOfBenefits) -> bytes:
        """
        Generate an Explanation of Benefits (EOB) statement PDF.
        Includes itemized line items, billed charges, allowed amounts (never 0 if unknown),
        deductible/copay/coinsurance breakdown, and financial reconciliation.
        """
        builder = PDFBuilder(
            title="Explanation of Benefits (EOB)",
            subtitle="Adjudication Statement & Audit Summary",
        )

        # 1. Claim Metadata
        gen_time = datetime.now(timezone.utc).strftime("%Y-%m-%d %H:%M UTC")
        meta_items = [
            ("Claim Reference", claim.claim_reference or claim.id[:12]),
            ("Policy Identifier", claim.policy_id[:12] if claim.policy_id else "Unattached Policy"),
            ("Incident Date", str(claim.incident_date)),
            ("Adjudication Date", gen_time),
            ("Bill Document Hash", (claim.bill_document_hash or "N/A")[:16] + "..."),
            ("Adjudication Status", claim.status.value.upper()),
        ]
        builder.add_info_grid(meta_items)

        # 2. Disclaimer
        builder.add_disclaimer_box(
            "This EOB statement is an illustrative cost-sharing model based strictly on parsed "
            "policy evidence and deterministic rules engine execution. It does NOT constitute an "
            "official bill or legal insurer payment determination."
        )

        # 3. Itemized Line Items Table
        builder.add_section_title("Itemized Bill Adjudication Line Items")

        # Table header
        col_widths = [24, 150, 50, 60, 60, 55, 55, 60]  # Total: 514
        headers = ["#", "Service Description", "CPT", "Billed", "Allowed", "Ded/Copay", "Coins.", "Member Owes"]
        
        builder.check_space(20)
        h_rect = pymupdf.Rect(builder.margin_x, builder.current_y, builder.page_width - builder.margin_x, builder.current_y + 16)
        builder.page.draw_rect(h_rect, color=NAVY_PRIMARY, fill=NAVY_PRIMARY)

        x_cur = builder.margin_x + 4
        for idx, h_text in enumerate(headers):
            builder.page.insert_text(
                pymupdf.Point(x_cur, builder.current_y + 11),
                h_text,
                fontname="helv",
                fontsize=7,
                color=WHITE,
            )
            x_cur += col_widths[idx]
        builder.current_y += 18

        # Line rows
        for i, item in enumerate(eob.items):
            builder.check_space(18)
            row_rect = pymupdf.Rect(builder.margin_x, builder.current_y, builder.page_width - builder.margin_x, builder.current_y + 16)
            row_fill = GRAY_BG if i % 2 == 0 else WHITE
            builder.page.draw_rect(row_rect, color=GRAY_BORDER, fill=row_fill)

            allowed_str = _format_cents(item.allowed_amount_cents) if item.allowed_amount_cents is not None else "Pending"
            ded_copay_cents = (item.deductible_applied_cents or 0) + (item.copay_cents or 0)

            cells = [
                str(i + 1),
                item.description[:32],
                item.cpt_code or "N/A",
                _format_cents(item.billed_charge_cents),
                allowed_str,
                _format_cents(ded_copay_cents),
                _format_cents(item.member_coinsurance_cents or 0),
                _format_cents(item.illustrative_member_cents),
            ]

            x_cur = builder.margin_x + 4
            for c_idx, cell_text in enumerate(cells):
                builder.page.insert_text(
                    pymupdf.Point(x_cur, builder.current_y + 11),
                    cell_text,
                    fontname="helv",
                    fontsize=7,
                    color=TEXT_DARK,
                )
                x_cur += col_widths[c_idx]
            builder.current_y += 17

        # 4. Financial Reconciliation Summary
        builder.add_section_title("Financial Cost-Sharing Totals & Reconciliation")
        totals_grid = [
            ("Total Billed Charges", _format_cents(eob.total_billed_cents)),
            ("Total Allowed Amount", _format_cents(eob.total_allowed_cents) if eob.total_allowed_cents is not None else "Unknown (Incomplete Evidence)"),
            ("Member Deductible Applied", _format_cents(eob.total_deductible_applied_cents)),
            ("Member Copay Total", _format_cents(eob.total_copay_cents)),
            ("Member Coinsurance Total", _format_cents(eob.total_member_coinsurance_cents)),
            ("Total Member Responsibility", _format_cents(eob.total_illustrative_member_cents)),
            ("Illustrative Insurer Share", _format_cents(eob.total_illustrative_insurer_cents)),
            ("Mathematical Integrity", "Verified (Deductible + Copay + Coinsurance = Member Total)"),
        ]
        builder.add_info_grid(totals_grid)

        # 5. Evidence Citations
        all_citations = []
        for it in eob.items:
            for c in it.evidence_citations:
                if c not in all_citations:
                    all_citations.append(c)

        if all_citations:
            builder.add_section_title("Retrieved Policy Evidence & Citations")
            for cit in all_citations[:4]:
                builder.check_space(34)
                cit_rect = pymupdf.Rect(builder.margin_x, builder.current_y, builder.page_width - builder.margin_x, builder.current_y + 28)
                builder.page.draw_rect(cit_rect, color=GRAY_BORDER, fill=WHITE)
                builder.page.insert_text(
                    pymupdf.Point(builder.margin_x + 8, builder.current_y + 11),
                    f"Clause {cit.clause_id} (Page {cit.page_number}): {cit.clause_heading or 'General Coverage'}",
                    fontname="helv",
                    fontsize=7,
                    color=NAVY_PRIMARY,
                )
                snippet = (cit.exact_quote or "")[:90] + "..."
                builder.page.insert_text(
                    pymupdf.Point(builder.margin_x + 8, builder.current_y + 22),
                    f"\"{snippet}\"",
                    fontname="helv",
                    fontsize=6,
                    color=TEXT_MUTED,
                )
                builder.current_y += 32

        return builder.doc.tobytes()

    @staticmethod
    def generate_appeal_pdf(draft: ClaimAppealDraft) -> bytes:
        """
        Generate a denial appeal letter PDF package.
        Enforces user-reviewed state requirement: raises ValueError if draft has not been reviewed.
        """
        if draft.status not in (AppealStatus.USER_EDITED, AppealStatus.EXPORTED, "user_edited", "reviewed", "exported"):
            raise ValueError(
                "Appeal draft must be reviewed and confirmed by user before PDF export can be generated."
            )

        builder = PDFBuilder(
            title="Denial Appeal & Reconsideration Package",
            subtitle="Evidence-Based Member Advocacy Statement",
        )

        # 1. Metadata Box
        gen_time = datetime.now(timezone.utc).strftime("%Y-%m-%d %H:%M UTC")
        meta_items = [
            ("Claim Identifier", draft.claim_id[:16]),
            ("Insurance Carrier", draft.insurer_name or "Target Insurer"),
            ("Denial Reason Code", draft.denial_reason_code or "Unspecified Denial"),
            ("Draft Status", draft.status.value.upper() if hasattr(draft.status, "value") else str(draft.status).upper()),
            ("Review Timestamp", gen_time),
            ("Verified Citations", str(len(draft.policy_clauses_cited))),
        ]
        builder.add_info_grid(meta_items)

        # 2. Disclaimer
        builder.add_disclaimer_box(
            "This document is an evidence-grounded appeal draft prepared for consumer advocacy. "
            "It does not constitute formal legal advice. The insured member is solely responsible "
            "for submitting this package to the insurer before relevant statutory appeal deadlines."
        )

        # 3. User-Requested Relief
        if draft.requested_action:
            builder.add_section_title("Requested Relief")
            builder.check_space(26)
            builder.page.insert_textbox(
                pymupdf.Rect(builder.margin_x + 4, builder.current_y, builder.page_width - builder.margin_x, builder.current_y + 22),
                draft.requested_action,
                fontname="helv",
                fontsize=8,
                color=TEXT_DARK,
            )
            builder.current_y += 28

        # 4. Appeal Letter Narrative
        builder.add_section_title("Formal Appeal Letter Statement")
        narrative_parts = [
            ("STATEMENT OF ISSUE", draft.statement_of_issue),
            ("FACTUAL BACKGROUND", draft.factual_background),
            ("REBUTTAL ARGUMENT & CLINICAL NECESSITY", draft.rebuttal_narrative),
        ]
        
        for section_title, section_text in narrative_parts:
            if not section_text:
                continue
            builder.check_space(20)
            builder.page.insert_text(
                pymupdf.Point(builder.margin_x + 4, builder.current_y + 10),
                section_title,
                fontname="helv",
                fontsize=8,
                color=NAVY_PRIMARY,
            )
            builder.current_y += 14

            paragraphs = section_text.split("\n\n")
            for para in paragraphs:
                para_clean = para.strip().replace("#", "").replace("*", "")
                if not para_clean:
                    continue
                builder.check_space(36)
                rect = pymupdf.Rect(builder.margin_x + 4, builder.current_y, builder.page_width - builder.margin_x, builder.current_y + 32)
                builder.page.insert_textbox(
                    rect,
                    para_clean,
                    fontname="helv",
                    fontsize=8,
                    color=TEXT_DARK,
                )
                builder.current_y += 38

        # 5. Policy Evidence & Citation Index
        if draft.policy_clauses_cited:
            builder.add_section_title("Supporting Policy Evidence & Citations")
            for cit in draft.policy_clauses_cited:
                builder.check_space(34)
                cit_rect = pymupdf.Rect(builder.margin_x, builder.current_y, builder.page_width - builder.margin_x, builder.current_y + 28)
                builder.page.draw_rect(cit_rect, color=GRAY_BORDER, fill=WHITE)
                builder.page.insert_text(
                    pymupdf.Point(builder.margin_x + 8, builder.current_y + 11),
                    f"Clause {cit.clause_id} (Page {cit.page_number}): {cit.clause_heading or 'Coverage Clause'}",
                    fontname="helv",
                    fontsize=7,
                    color=NAVY_PRIMARY,
                )
                quote_snip = (cit.exact_quote or "")[:90] + "..."
                builder.page.insert_text(
                    pymupdf.Point(builder.margin_x + 8, builder.current_y + 22),
                    f"\"{quote_snip}\"",
                    fontname="helv",
                    fontsize=6,
                    color=TEXT_MUTED,
                )
                builder.current_y += 32

        # 6. Missing Evidence Checklist
        if draft.missing_documents_checklist:
            builder.add_section_title("Evidence Submission Checklist")
            for item in draft.missing_documents_checklist:
                builder.check_space(18)
                status_icon = "[X]" if item.is_available else "[ ]"
                item_color = NAVY_PRIMARY if item.is_available else AMBER_WARNING
                builder.page.insert_text(
                    pymupdf.Point(builder.margin_x + 6, builder.current_y + 11),
                    f"{status_icon}  {item.item_name} ({'Available' if item.is_available else 'Pending / Action Required'}): {item.description[:70]}",
                    fontname="helv",
                    fontsize=7,
                    color=item_color,
                )
                builder.current_y += 16

        return builder.doc.tobytes()

    @staticmethod
    def generate_comparison_pdf(record: ComparisonRecord) -> bytes:
        """
        Generate a Multi-Policy Comparison Report PDF.
        Includes side-by-side attributes, evidence status markers, cost simulation, and citations.
        """
        builder = PDFBuilder(
            title="Multi-Policy Comparison Report",
            subtitle="Side-by-Side Benefit & Cost Evaluation Matrix",
        )

        # 1. Metadata Box
        gen_time = datetime.now(timezone.utc).strftime("%Y-%m-%d %H:%M UTC")
        meta_items = [
            ("Comparison Report", record.title),
            ("Comparison ID", record.id[:16]),
            ("Evaluated Policies", str(len(record.policies))),
            ("Report Timestamp", gen_time),
            ("Status", record.status.upper()),
            ("Analysis Neutrality", "Verified (No plan labeled best without evidence)"),
        ]
        builder.add_info_grid(meta_items)

        # 2. Disclaimer
        builder.add_disclaimer_box(
            "This comparison matrix is derived deterministically from parsed policy documents. "
            "Unknown or conflicting values are explicitly identified and never assumed to be zero. "
            "Review official summary of benefits and coverage (SBC) before open enrollment decisions."
        )

        # 3. Policy Headers
        builder.add_section_title("Evaluated Policies")
        for p in record.policies:
            builder.check_space(20)
            p_name = getattr(p, "policy_name", None) or getattr(p, "title", "Policy")
            p_hash = getattr(p, "document_hash", None) or getattr(p, "document_sha256", "N/A")
            builder.page.insert_text(
                pymupdf.Point(builder.margin_x + 6, builder.current_y + 11),
                f"• {p_name} ({p.insurer_name})  —  Hash: {p_hash[:16]}...",
                fontname="helv",
                fontsize=8,
                color=NAVY_PRIMARY,
            )
            builder.current_y += 16

        # 4. Attribute Comparison Table
        builder.add_section_title("Side-by-Side Coverage Attributes")
        
        num_policies = max(len(record.policies), 1)
        avail_width = builder.content_width - 130
        p_col_width = avail_width / num_policies

        # Table header
        builder.check_space(20)
        h_rect = pymupdf.Rect(builder.margin_x, builder.current_y, builder.page_width - builder.margin_x, builder.current_y + 16)
        builder.page.draw_rect(h_rect, color=NAVY_PRIMARY, fill=NAVY_PRIMARY)

        builder.page.insert_text(
            pymupdf.Point(builder.margin_x + 6, builder.current_y + 11),
            "Attribute",
            fontname="helv",
            fontsize=7,
            color=WHITE,
        )
        for p_idx, p in enumerate(record.policies):
            x_pos = builder.margin_x + 130 + (p_idx * p_col_width)
            p_name = getattr(p, "policy_name", None) or getattr(p, "title", "Policy")
            builder.page.insert_text(
                pymupdf.Point(x_pos + 4, builder.current_y + 11),
                p_name[:16],
                fontname="helv",
                fontsize=7,
                color=WHITE,
            )
        builder.current_y += 18

        # Collect attribute keys across all policy cards
        attr_keys: List[str] = []
        for p in record.policies:
            for k in p.attributes.keys():
                if k not in attr_keys:
                    attr_keys.append(k)

        # Rows
        for r_idx, attr_key in enumerate(attr_keys):
            builder.check_space(18)
            row_rect = pymupdf.Rect(builder.margin_x, builder.current_y, builder.page_width - builder.margin_x, builder.current_y + 16)
            row_fill = GRAY_BG if r_idx % 2 == 0 else WHITE
            builder.page.draw_rect(row_rect, color=GRAY_BORDER, fill=row_fill)

            display_label = attr_key.replace("_", " ").title()
            for p in record.policies:
                if attr_key in p.attributes and p.attributes[attr_key].display_name:
                    display_label = p.attributes[attr_key].display_name
                    break

            builder.page.insert_text(
                pymupdf.Point(builder.margin_x + 6, builder.current_y + 11),
                display_label[:24],
                fontname="helv",
                fontsize=7,
                color=TEXT_DARK,
            )

            for p_idx, p in enumerate(record.policies):
                val_obj = p.attributes.get(attr_key)
                disp_val = "Unknown"
                if val_obj:
                    if val_obj.status == "verified":
                        disp_val = str(val_obj.raw_value or val_obj.numeric_value_cents or "Verified")
                    elif val_obj.status == "unknown":
                        disp_val = "Unknown (?)"
                    elif val_obj.status == "conflicting":
                        disp_val = "Conflict (!)"
                    else:
                        disp_val = str(val_obj.raw_value or "N/A")

                x_pos = builder.margin_x + 130 + (p_idx * p_col_width)
                builder.page.insert_text(
                    pymupdf.Point(x_pos + 4, builder.current_y + 11),
                    disp_val[:18],
                    fontname="helv",
                    fontsize=7,
                    color=TEXT_DARK,
                )
            builder.current_y += 17

        # 5. Cost Simulation
        if record.cost_simulation:
            builder.add_section_title("Illustrative Cost Simulation")
            sim = record.cost_simulation
            assump_text = (
                f"Assumptions: Service: {sim.assumptions.service_type}  |  "
                f"Billed: {_format_cents(sim.assumptions.billed_charges_cents)}  |  "
                f"Network: {sim.assumptions.network_status}"
            )
            builder.check_space(20)
            builder.page.insert_text(
                pymupdf.Point(builder.margin_x + 6, builder.current_y + 11),
                assump_text,
                fontname="helv",
                fontsize=7,
                color=TEXT_MUTED,
            )
            builder.current_y += 18

            for pres in sim.policy_estimates:
                builder.check_space(18)
                oop_str = _format_cents(pres.member_responsibility_cents) if pres.is_complete else "Incomplete (Unknowns)"
                ded_str = _format_cents(pres.deductible_portion_cents) if pres.deductible_portion_cents is not None else "N/A"
                builder.page.insert_text(
                    pymupdf.Point(builder.margin_x + 6, builder.current_y + 11),
                    f"• {pres.policy_name}: Est. Member OOP: {oop_str}  (Deductible: {ded_str})",
                    fontname="helv",
                    fontsize=8,
                    color=NAVY_PRIMARY,
                )
                builder.current_y += 16

        return builder.doc.tobytes()


pdf_export_service = PDFExportService()
