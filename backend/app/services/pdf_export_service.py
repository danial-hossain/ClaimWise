"""Server-Side PDF Export System using PyMuPDF.

Generates professional, server-side PDF documents for:
1. Explanation of Benefits (EOB) statements
2. Reviewed Denial Appeal Letters
3. Multi-Policy Comparison Reports

Aesthetics: Clean professional styling, brand navy/blue color palette, itemized tables,
evidentiary citation boxes, integer-cents financial reconciliation, and prominent disclaimers.
"""

